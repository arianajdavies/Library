function extendBookCatalog(catalog) {
  const normalize = value => value.toLowerCase().replace(/[^a-z0-9]/g, '');
  catalog.forEach(book => {
    const update = existingBookUpdates[book.title];
    if (!update) return;
    const sources = [...book.sources, ...(update.sources || [])];
    Object.assign(book, update, {
      sources: sources.filter((source, index) => sources.findIndex(other => other.url === source.url) === index),
      aliases: [...new Set([...(book.aliases || []), ...(update.aliases || [])])]
    });
  });
  additionalBooks.forEach(book => {
    const duplicate = catalog.some(existing => normalize(existing.title) === normalize(book.title) && normalize(existing.author) === normalize(book.author));
    if (!duplicate) catalog.push({ ...book, coverQuery: book.title + ' ' + book.author });
  });
}
