function applyBookMetadata(catalog) {
  catalog.forEach(book => {
    const metadata = bookMetadata[book.title];
    if (!metadata) return;
    book.genres = metadata.genres;
    book.seriesFocus = metadata.seriesFocus;
    book.seriesFocusNote = metadata.seriesFocusNote;
    book.coverPath = metadata.coverPath;
    book.coverSource = metadata.coverSource;
    book.coverUrls = [];
    const invalidOldSources = ['/books/772770/', '/books/100124/', '/books/288728/'];
    const sources = [...book.sources, ...(metadata.sources || [])].filter(source => !invalidOldSources.some(fragment => source.url.includes(fragment)));
    book.sources = sources.filter((source,index) => sources.findIndex(other => other.url === source.url) === index);
    if (!book.sources.length) book.sources.push({label:'Publisher',url:book.coverSource});
  });
}
